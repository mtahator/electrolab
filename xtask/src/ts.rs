//! TypeScript from the committed JSON Schemas (ADR-004, P1.M1.GEN.1).
//!
//! Reads `spec/schemas/*.json` (one file per command, plus `_bus.json`) and writes:
//! - `ui/bindings/src/types.ts`    every named type (`$defs` and titled roots)
//! - `ui/bindings/src/commands.ts` `Commands` map: name → { input; output }
//!
//! Supports the JSON Schema subset `schemars` produces: `$ref`, `$defs`, `type` (also as an
//! array), `properties`/`required`, `additionalProperties`, `items`, `enum`, `const`,
//! `oneOf`/`anyOf`/`allOf`, `description`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde_json::{Map, Value};

const HEADER: &str = "// Generated by `cargo xtask gen` from spec/schemas. Do not edit by hand.\n";

fn is_ident(s: &str) -> bool {
    s.chars()
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn key(s: &str) -> String {
    if is_ident(s) {
        s.to_string()
    } else {
        format!("{s:?}")
    }
}

fn doc(out: &mut String, indent: &str, d: Option<&Value>) {
    if let Some(text) = d.and_then(Value::as_str) {
        let text = text.replace("*/", "* /");
        let lines: Vec<&str> = text.lines().collect();
        if lines.len() == 1 {
            let _ = writeln!(out, "{indent}/** {} */", lines[0]);
        } else {
            let _ = writeln!(out, "{indent}/**");
            for l in lines {
                let _ = writeln!(out, "{indent} * {l}").map(|()| ());
            }
            let _ = writeln!(out, "{indent} */");
        }
    }
}

fn ref_name(r: &str) -> String {
    r.rsplit('/').next().unwrap_or(r).to_string()
}

fn union(parts: Vec<String>) -> String {
    let mut seen = Vec::new();
    for p in parts {
        if !seen.contains(&p) {
            seen.push(p);
        }
    }
    if seen.is_empty() {
        "never".into()
    } else {
        seen.join(" | ")
    }
}

fn paren(t: &str) -> String {
    if t.contains(" | ") || t.contains(" & ") {
        format!("({t})")
    } else {
        t.to_string()
    }
}

/// TypeScript type expression for a schema.
pub fn ts_type(s: &Value, indent: usize) -> String {
    let Some(o) = s.as_object() else {
        return if s == &Value::Bool(false) {
            "never".into()
        } else {
            "unknown".into()
        };
    };
    if let Some(r) = o.get("$ref").and_then(Value::as_str) {
        return ref_name(r);
    }
    if let Some(c) = o.get("const") {
        return c.to_string();
    }
    if let Some(e) = o.get("enum").and_then(Value::as_array) {
        return union(e.iter().map(Value::to_string).collect());
    }
    for k in ["oneOf", "anyOf"] {
        if let Some(v) = o.get(k).and_then(Value::as_array) {
            // Properties next to oneOf (internally tagged enums put shared fields there).
            let base = object_without(o, &[k, "description", "title", "$schema", "$defs"]);
            let parts: Vec<String> = v.iter().map(|x| ts_type(x, indent)).collect();
            let u = union(parts);
            return if base.is_empty() || base.keys().all(|k| k == "type") {
                u
            } else {
                format!("{} & ({u})", ts_type(&Value::Object(base), indent))
            };
        }
    }
    if let Some(v) = o.get("allOf").and_then(Value::as_array) {
        return v
            .iter()
            .map(|x| paren(&ts_type(x, indent)))
            .collect::<Vec<_>>()
            .join(" & ");
    }
    match o.get("type") {
        Some(Value::Array(types)) => union(
            types
                .iter()
                .map(|t| {
                    let mut one = o.clone();
                    one.insert("type".into(), t.clone());
                    ts_type(&Value::Object(one), indent)
                })
                .collect(),
        ),
        Some(Value::String(t)) => match t.as_str() {
            "string" => "string".into(),
            "integer" | "number" => "number".into(),
            "boolean" => "boolean".into(),
            "null" => "null".into(),
            "array" => match o.get("items") {
                Some(items) => format!("{}[]", paren(&ts_type(items, indent))),
                None => match o.get("prefixItems").and_then(Value::as_array) {
                    Some(p) => format!(
                        "[{}]",
                        p.iter()
                            .map(|x| ts_type(x, indent))
                            .collect::<Vec<_>>()
                            .join(", ")
                    ),
                    None => "unknown[]".into(),
                },
            },
            "object" => object_type(o, indent),
            _ => "unknown".into(),
        },
        _ if o.contains_key("properties") => object_type(o, indent),
        _ => "unknown".into(),
    }
}

fn object_without(o: &Map<String, Value>, drop: &[&str]) -> Map<String, Value> {
    o.iter()
        .filter(|(k, _)| !drop.contains(&k.as_str()))
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect()
}

fn object_type(o: &Map<String, Value>, indent: usize) -> String {
    let props = o.get("properties").and_then(Value::as_object);
    let extra = o.get("additionalProperties").filter(|v| v.is_object());
    let Some(props) = props.filter(|p| !p.is_empty()) else {
        return extra.map_or_else(
            || "Record<string, unknown>".into(),
            |e| format!("Record<string, {}>", ts_type(e, indent)),
        );
    };
    let required: Vec<&str> = o
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let pad = "  ".repeat(indent + 1);
    let mut out = String::from("{\n");
    for (name, p) in props {
        doc(&mut out, &pad, p.get("description"));
        let opt = if required.contains(&name.as_str()) {
            ""
        } else {
            "?"
        };
        let _ = writeln!(out, "{pad}{}{opt}: {};", key(name), ts_type(p, indent + 1));
    }
    let _ = write!(out, "{}}}", "  ".repeat(indent));
    out
}

struct Collected {
    types: BTreeMap<String, Value>,
    commands: Vec<(String, String, String, Option<String>)>,
}

/// A schema without the keys that differ between a root and the same type under `$defs`.
fn strip(s: &Value) -> Value {
    let mut body = s.clone();
    if let Some(m) = body.as_object_mut() {
        for k in ["$defs", "$schema", "title"] {
            m.remove(k);
        }
    }
    body
}

fn named_root(s: &Value, types: &mut BTreeMap<String, Value>) -> String {
    let title = s.get("title").and_then(Value::as_str).unwrap_or_default();
    let is_named = is_ident(title)
        && s.get("type")
            .and_then(Value::as_str)
            .is_some_and(|t| t == "object")
        || s.get("oneOf").is_some();
    let body = strip(s);
    if is_named && is_ident(title) {
        types.insert(title.to_string(), body);
        title.to_string()
    } else {
        ts_type(&body, 0)
    }
}

fn collect(dir: &Path) -> anyhow::Result<Collected> {
    let mut files: Vec<_> = std::fs::read_dir(dir)?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    let mut c = Collected {
        types: BTreeMap::new(),
        commands: vec![],
    };
    for f in files {
        let v: Value = serde_json::from_str(&std::fs::read_to_string(&f)?)?;
        let add_defs = |s: &Value, c: &mut Collected| -> anyhow::Result<()> {
            if let Some(defs) = s.get("$defs").and_then(Value::as_object) {
                for (k, d) in defs {
                    let d = strip(d);
                    if let Some(old) = c.types.get(k)
                        && old != &d
                    {
                        anyhow::bail!(
                            "type {k} has two different definitions (seen in {})",
                            f.display()
                        );
                    }
                    c.types.insert(k.clone(), d);
                }
            }
            Ok(())
        };
        if let Some(name) = v.get("command").and_then(Value::as_str) {
            let (input, output) = (&v["input"], &v["output"]);
            add_defs(input, &mut c)?;
            add_defs(output, &mut c)?;
            let i = named_root(input, &mut c.types);
            let o = named_root(output, &mut c.types);
            c.commands.push((
                name.to_string(),
                i,
                o,
                v.get("summary").and_then(Value::as_str).map(str::to_string),
            ));
        } else if let Some(defs) = v.get("types").and_then(Value::as_object) {
            for s in defs.values() {
                add_defs(s, &mut c)?;
                named_root(s, &mut c.types);
            }
        }
    }
    Ok(c)
}

/// Generate the TypeScript files from the schemas in `schemas` into `out`.
pub fn generate(schemas: &Path, out: &Path) -> anyhow::Result<()> {
    let c = collect(schemas)?;
    let mut types = String::from(HEADER);
    for (name, s) in &c.types {
        types.push('\n');
        doc(&mut types, "", s.get("description"));
        let t = ts_type(s, 0);
        if t.starts_with('{') && !t.contains(" | ") {
            let _ = writeln!(types, "export interface {name} {t}");
        } else {
            let _ = writeln!(types, "export type {name} = {t};");
        }
    }
    let mut cmds = String::from(HEADER);
    cmds.push_str("import type * as T from \"./types\";\n\n/** Every command: its input and output types. */\nexport interface Commands {\n");
    let qualify = |t: &str| -> String {
        // Prefix generated type names with `T.`; leave primitives and literals alone.
        let mut out = String::new();
        let mut word = String::new();
        let flush = |w: &mut String, out: &mut String| {
            if !w.is_empty() {
                let prim = [
                    "string", "number", "boolean", "null", "unknown", "never", "Record", "true",
                    "false",
                ]
                .contains(&w.as_str());
                if !prim && w.chars().next().is_some_and(char::is_uppercase) {
                    out.push_str("T.");
                }
                out.push_str(w);
                w.clear();
            }
        };
        let mut in_str = false;
        for ch in t.chars() {
            if ch == '"' {
                in_str = !in_str;
            }
            if !in_str && (ch.is_ascii_alphanumeric() || ch == '_') {
                word.push(ch);
            } else {
                flush(&mut word, &mut out);
                out.push(ch);
            }
        }
        flush(&mut word, &mut out);
        out
    };
    for (name, i, o, summary) in &c.commands {
        if let Some(s) = summary {
            let _ = writeln!(cmds, "  /** {s} */");
        }
        let _ = writeln!(
            cmds,
            "  {name:?}: {{ input: {}; output: {} }};",
            qualify(i),
            qualify(o)
        );
    }
    cmds.push_str("}\n\n/** A command name. */\nexport type CommandName = keyof Commands;\n");
    std::fs::create_dir_all(out)?;
    std::fs::write(out.join("types.ts"), types)?;
    std::fs::write(out.join("commands.ts"), cmds)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn schema_subset_to_typescript() {
        assert_eq!(
            ts_type(&json!({ "type": ["string", "null"] }), 0),
            "string | null"
        );
        assert_eq!(
            ts_type(
                &json!({ "type": "array", "items": { "$ref": "#/$defs/Paper" } }),
                0
            ),
            "Paper[]"
        );
        assert_eq!(ts_type(&json!({ "enum": ["a", "b"] }), 0), "\"a\" | \"b\"");
        assert_eq!(
            ts_type(
                &json!({ "anyOf": [{ "$ref": "#/$defs/X" }, { "type": "null" }] }),
                0
            ),
            "X | null"
        );
        let obj = ts_type(
            &json!({ "type": "object", "properties": { "a": { "type": "integer" }, "b-c": { "type": "string" } }, "required": ["a"] }),
            0,
        );
        assert_eq!(obj, "{\n  a: number;\n  \"b-c\"?: string;\n}");
        assert_eq!(
            ts_type(
                &json!({ "type": "object", "additionalProperties": { "type": "number" } }),
                0
            ),
            "Record<string, number>"
        );
    }
}
